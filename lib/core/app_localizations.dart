import 'package:flutter/widgets.dart';

import 'package:carelink/core/locale_controller.dart';

class CarelinkL10n {
  const CarelinkL10n(this.locale);

  final Locale locale;

  bool get isArabic => locale.languageCode == 'ar';

  /// Uses [localeController] so toggling AR/EN updates every [tr]/[l10n] call
  /// reliably (does not rely on inherited [Localizations] edge cases).
  static CarelinkL10n of(BuildContext _) {
    return CarelinkL10n(localeController.locale);
  }

  static CarelinkL10n doctor(BuildContext _) {
    return CarelinkL10n(localeController.doctorLocale);
  }

  String t(String key, {Map<String, String>? args}) {
    var value = (isArabic ? _ar : _en)[key] ?? _en[key] ?? key;
    if (args != null) {
      for (final entry in args.entries) {
        value = value.replaceAll('{${entry.key}}', entry.value);
      }
    }
    return value;
  }
}

extension CarelinkL10nX on BuildContext {
  CarelinkL10n get l10n => CarelinkL10n.of(this);
  CarelinkL10n get doctorL10n => CarelinkL10n.doctor(this);

  String tr(String key, {Map<String, String>? args}) {
    return l10n.t(key, args: args);
  }

  String dtr(String key, {Map<String, String>? args}) {
    return doctorL10n.t(key, args: args);
  }
}

